// build 1387: the two engine surfaces get an AUTHORED normal map, off the same height field as their albedo.
//
// The critic's second verified finding was that `PROC_SLOTS` feeds only the procedural value-noise field,
// so no authored normal or roughness map is loaded anywhere in the level. Build 1378 gave the ground and
// the boundary walls a real albedo and left `floorTexN`/`wallTexN` empty — so the surface had structure in
// its colour and unrelated micro-noise in its relief, which is a printed photograph with bumps on it.
//
// THE WHOLE DESIGN CLAIM IS CORRELATION, and it is what this test proves: the normal map is generated by
// the SAME `make()` call, at the same size and seed, as the albedo that ships beside it — so the crack in
// the albedo and the crease in the normal are the same crack. Re-derived here from the real generator, the
// way builds 1151 / 1378 / 1384 re-derive their constants, because a normal map that drifts from its
// albedo is worse than none and would drift silently.
import { readFileSync, statSync } from 'node:fs';
import { gameSource, assert, near, eq, done } from './harness.mjs';
import { pngDecode } from './albedo.mjs';

const src = gameSource();
const lgSrc = readFileSync(new URL('../tools/levelgen.mjs', import.meta.url), 'utf8').replace(/^#![^\n]*\n/, '');
const AsyncFn = Object.getPrototypeOf(async function(){}).constructor;
const api = await new AsyncFn('RUMPUS_LEVELGEN_HOST', 'Buffer', 'process',
  lgSrc + '\n;return { MATLIB, normalPx, halfPx, toBytes, pngEncode };')(
  { deflateSync: () => new Uint8Array(0), writeFileSync: () => {} }, Buffer, process);

const PAIRS = [
  { lib: 'concrete', alb: 'img/tex/floor-concrete.png', nrm: 'img/tex/floor-concrete-n.png', cfg: 'floor' },
  { lib: 'panels',   alb: 'img/tex/wall-panels.png',    nrm: 'img/tex/wall-panels-n.png',    cfg: 'wall'  },
];
const at = (rel) => new URL('../' + rel, import.meta.url).pathname;

// ------------------------------------------------- the engine points at them ----
{
  for(const p of PAIRS){
    const re = new RegExp(p.cfg + "TexN:'" + p.nrm.replace(/[/.\-]/g, '\\$&') + "'");
    assert(re.test(src), 'DEFAULT_WORLD.' + p.cfg + 'TexN is ' + p.nrm);
    assert(new RegExp(p.cfg + "Tex:'" + p.alb.replace(/[/.\-]/g, '\\$&') + "'").test(src),
      '...beside the albedo it was generated with');
    assert(statSync(at(p.nrm)).size < 60 * 1024,
      p.nrm + ' is ' + (statSync(at(p.nrm)).size / 1024 | 0) + ' KB — half-res aux, the generator\'s own convention');
  }
  // The ROUGHNESS slot stays empty ON PURPOSE, and this is the honest half of the finding: neither
  // `concrete` nor `panels` carries an `mr` field in the library (about half of the 34 entries do), so
  // there is nothing to source a roughness map FROM. Inventing one from the height field would be making
  // data up. An empty slot is not a hole — `_procFallback` restores build 1139's procedural roughness.
  assert(/floorTexR:''/.test(src) && /wallTexR:''/.test(src), 'the roughness slots stay empty');
  for(const p of PAIRS){
    const t = api.MATLIB[p.lib].make('t_' + p.lib, 32);
    assert(t.h, p.lib + ' has a height field to derive a normal from');
    assert(!t.mr, '...and no mr field, which is why no roughness map ships for it');
  }
}

// --------------------------- the shipped normal IS this albedo's own height field ----
// Re-derived end to end: same make(), same size, same strength convention as the glTF bake, same
// downsample. If a future edit regenerates one of the pair without the other, this fails.
{
  const S = 256;
  for(const p of PAIRS){
    const t = api.MATLIB[p.lib].make('t_' + p.lib, S);
    eq(t.S !== undefined ? t.S : S, S, p.lib + ' generated at ' + S + 'px');

    // 1. the ALBEDO regenerates PIXEL-IDENTICALLY — that is what makes "the same field" mean anything.
    //    Compared as decoded pixels rather than as compressed bytes: the PNG encoder needs the host's
    //    deflate, and testing zlib's output is not testing this build.
    const albDec = pngDecode(readFileSync(at(p.alb)));
    const albHere = api.toBytes(t.rgb);
    eq(albDec.w + 'x' + albDec.h, S + 'x' + S, p.alb + ' is ' + S + 'px');
    let albWorst = 0;
    for(let i = 0; i < S * S; i++) for(let c = 0; c < 3; c++)
      albWorst = Math.max(albWorst, Math.abs(albDec.data[i * albDec.ch + c] - albHere[i * 3 + c]));
    eq(albWorst, 0, p.alb + ' regenerates EXACTLY from make(), so the height field below is provably its own');

    // 2. the NORMAL map, by the glTF bake's own convention: 2.2 * S/256 (world-space relief constant
    //    across resolutions) times the library entry's `nrm`, then halved.
    const nrmScale = api.MATLIB[p.lib].opts.nrm;
    assert(nrmScale > 0, p.lib + ' names its own normal strength (' + nrmScale + ')');
    let q = api.normalPx(t.h, S, 2.2 * S / 256 * nrmScale), ss = S;
    q = api.halfPx(q, ss, 3); ss >>= 1;
    const mine = api.toBytes(q);

    const dec = pngDecode(readFileSync(at(p.nrm)));
    eq(dec.w, ss, p.nrm + ' is ' + ss + 'x' + ss);
    eq(dec.h, ss, '...square');
    let worst = 0, n = ss * ss;
    for(let i = 0; i < n; i++) for(let c = 0; c < 3; c++)
      worst = Math.max(worst, Math.abs(dec.data[i * dec.ch + c] - mine[i * 3 + c]));
    eq(worst, 0, p.nrm + ' matches the re-derivation EXACTLY (worst channel delta ' + worst + ')');

    // 3. and it is a tangent-space normal map, not an accident: z dominant, xy centred on 0.5
    let mx = 0, my = 0, mz = 0;
    for(let i = 0; i < n; i++){ mx += dec.data[i*dec.ch]; my += dec.data[i*dec.ch+1]; mz += dec.data[i*dec.ch+2]; }
    near(mx / n / 255, 0.5, 0.03, p.lib + ' normal: X centred on 0.5');
    near(my / n / 255, 0.5, 0.03, '...Y centred on 0.5');
    assert(mz / n / 255 > 0.85, '...Z dominant (' + (mz/n/255).toFixed(3) + ') — a tangent-space map, mostly facing out');
  }
}

// ------------------------------------------------- the generator emits them ----
{
  assert(/const nrmScale = \(MATLIB\[id\]\.opts && MATLIB\[id\]\.opts\.nrm\) \|\| 1;/.test(lgSrc),
    'the tex CLI reads the library entry\'s own normal strength');
  assert(/normalPx\(t\.h, S2, 2\.2 \* S2 \/ 256 \* nrmScale\)/.test(lgSrc),
    '...and uses the glTF bake\'s strength convention verbatim, so an engine surface and a generated arena ' +
    'agree about how deep a concrete crack is');
  assert(/writeFileSync\(stem \+ '-n\.png'/.test(lgSrc) && /writeFileSync\(stem \+ '-r\.png'/.test(lgSrc),
    'both aux maps are written beside the albedo');
  assert(/px\[i \* 3 \+ 1\] = t\.mr\[i \* 2\]; px\[i \* 3 \+ 2\] = t\.mr\[i \* 2 \+ 1\];/.test(lgSrc),
    'the MR map keeps glTF packing — roughness in G, metalness in B — which is also what three reads for ' +
    'roughnessMap (green) and metalnessMap (blue), so ONE image serves both slots');
  assert(/process\.env\.TEXAUX \|\| 2/.test(lgSrc), 'TEXAUX still controls the aux divisor');
  assert(/!process\.env\.NONRM/.test(lgSrc) && /!process\.env\.NOMR/.test(lgSrc),
    '...and the bisection knobs still work on the fast path');
  // the glTF bake is UNTOUCHED — every generated arena must keep the exact aux maps it had
  assert(/const \[q2, s2\] = down\(normalPx\(t\.h, S, 2\.2 \* S \/ 256\), S\);/.test(lgSrc),
    'the arena bake\'s own normal line is unchanged (it applies `nrm` as a glTF normalTexture scale instead)');
}

// -------------------------------------------- how the engine loads it ----
{
  assert(/_loadSurfaceMap\(mat, 'normalMap',\s+normalUrl, repU, repV, false,\s*rot\);/.test(src),
    'the normal map is loaded LINEAR — srgb false. Decoding it would bend every normal it carries');
  assert(/_loadSurfaceMap\(mat, 'map',\s+url,\s+repU, repV, true,\s*rot\);/.test(src),
    '...while the albedo beside it is sRGB');
  // build 1139's rule: relief is baked into the map, never left to material.normalScale, because
  // floorMat/wallMat are SHARED and a creator's own normal map would inherit whatever scale was left.
  const spec = src.match(/^\s*\w+(\.\w+)*\.normalScale[.\s]/gm) || [];
  eq(spec.length, 0, 'and nothing writes normalScale on a shared surface material (build 1139)');
  // the tiling is the same one the albedo gets, or the relief would slide off its own colour
  assert(/applySurfaceTexture\(floorMat, worldCfg\.floorTex, '_floorTexUrl', fu, fv, worldCfg\.floorTexN, worldCfg\.floorTexR/.test(src),
    'the normal map takes the albedo\'s own repeat and rotation — one call, one tiling');
}

done('build 1387: the ground and the walls get relief that describes the same surface as their colour');
